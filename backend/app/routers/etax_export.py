@router.get("/pdf/payment-voucher/{client_id}")
def download_payment_voucher_pdf(
    client_id: int,
    payment_type: str = "Quarterly Estimated Tax Payment",
    quarter_label: str = "",
    tax_year: int = 0,
    due_date: str = "",
    amount: float = 0,
    db: Session = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Auto-populate a printable BIR payment voucher.

    Query-string driven rather than a full return lookup: quarterly
    estimated tax / statutory levy vouchers are frequently a standalone
    "I know the amount, print me a slip" action rather than something tied
    to a stored return.
    """
    client = get_accessible_client(client_id, db, current_user)
    voucher = {
        "payment_type": payment_type,
        "quarter_label": quarter_label,
        "tax_year": tax_year,
        "due_date": due_date,
        "amount": amount,
        "bir_account_reference": f"{(client.bir_number or '0000000000').zfill(10)}-{tax_year}-{quarter_label or 'NA'}",
    }
    content = pdf_service.generate_payment_voucher_pdf(
        {"display_name": client.display_name, "bir_number": client.bir_number}, voucher
    )
    generated = GeneratedFile(
        file_name=f"PaymentVoucher_{client.display_name.replace(' ', '_')}_{tax_year}_{quarter_label or 'NA'}.pdf",
        content_bytes=content,
        row_count=1,
        validation_status=ValidationStatus.PASSED,
        validation_messages=["TaxTrin-branded payment voucher summary (see NOTES.md for scope)."],
    )
    _log_export(db, client.id, current_user.id, ETaxExportType.PAYMENT_VOUCHER_PDF, generated, tax_year or None, {"voucher": voucher})

    return Response(
        content=content,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{generated.file_name}"'},
    )


@router.get("/pdf/payroll-summary/{run_id}")
def download_payroll_summary_pdf(run_id: int, db: Session = Depends(get_db), current_user: User = Depends(get_current_user)):
    run = db.get(PayrollRun, run_id)
    if not run:
        raise HTTPException(status_code=404, detail="Payroll run not found")
    client = get_accessible_client(run.client_id, db, current_user)

    lines = [
        {
            "employee_name": line.employee_name,
            "gross_pay": float(line.gross_pay),
            "nis_employee": float(line.nis_employee),
            "nis_employer": float(line.nis_employer),
            "health_surcharge_employee": float(line.health_surcharge_employee),
            "health_surcharge_employer": float(line.health_surcharge_employer),
            "paye_deducted": float(line.paye_deducted),
            "net_pay": float(line.net_pay),
        }
        for line in run.lines
    ]
    period_label = f"{run.pay_period_start} to {run.pay_period_end}"
    content = pdf_service.generate_payroll_summary_pdf({"display_name": client.display_name}, period_label, lines)

    generated = GeneratedFile(
        file_name=f"PayrollSummary_{client.display_name.replace(' ', '_')}_{run.pay_period_start}.pdf",
        content_bytes=content,
        row_count=len(lines),
        validation_status=ValidationStatus.PASSED,
        validation_messages=["TaxTrin-branded payroll summary PDF (see NOTES.md for scope)."],
    )
    _log_export(db, client.id, current_user.id, ETaxExportType.PAYROLL_SUMMARY_PDF, generated, int(run.pay_period_start[:4]), {"payroll_run_id": run.id})

    return Response(
        content=content,
        media_type="application/pdf",
        headers={"Content-Disposition": f'attachment; filename="{generated.file_name}"'},
    )
