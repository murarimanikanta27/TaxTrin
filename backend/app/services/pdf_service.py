# VAT 200 summary
# ---------------------------------------------------------------------------


def generate_vat200_pdf(client: dict, period_start: str, period_end: str, computed: dict) -> bytes:
    elements = _header(
        "Form VAT 200 - Value Added Tax Return (Summary)",
        [
            f"Period {period_start} to {period_end}",
            f"{client.get('display_name', '')} &nbsp;|&nbsp; BIR File No. {client.get('bir_number', 'N/A')}",
        ],
    )

    elements.append(Paragraph("Sales", _SECTION))
    elements.append(
        _kv_table(
            [
                ("Description", "Amount"),
                ("Standard-rated sales", _money(computed.get("standard_rated_sales"))),
                ("Zero-rated sales", _money(computed.get("zero_rated_sales"))),
                ("Exempt sales", _money(computed.get("exempt_sales"))),
            ]
        )
    )

    elements.append(Paragraph("VAT Computation", _SECTION))
    balance_label = "VAT refund due" if computed.get("is_refund") else "Net VAT payable"
    elements.append(
        _kv_table(
            [
                ("Description", "Amount"),
                ("Output VAT", _money(computed.get("output_vat"))),
                ("Input VAT", _money(computed.get("input_vat"))),
                (balance_label, _money(abs(computed.get("net_vat_payable", 0)))),
            ]
        )
    )

    return _render(elements)


# ---------------------------------------------------------------------------
# BIR Payment Voucher (quarterly estimated tax / statutory levies)
# ---------------------------------------------------------------------------


def generate_payment_voucher_pdf(client: dict, voucher: dict) -> bytes:
    """`voucher` keys: payment_type, tax_year, quarter_label, due_date, amount,
    bir_account_reference."""
    elements = _header(
        "BIR Payment Voucher (Summary)",
        [
            f"{voucher.get('payment_type', 'Estimated Tax Payment')} &nbsp;|&nbsp; {voucher.get('quarter_label', '')}",
        ],
    )
    elements.append(
        _kv_table(
            [
                ("Description", "Detail"),
                ("Taxpayer", client.get("display_name", "")),
                ("BIR File No.", client.get("bir_number", "N/A")),
                ("BIR Account Reference", voucher.get("bir_account_reference", "N/A")),
                ("Tax Year", str(voucher.get("tax_year", ""))),
                ("Due Date", voucher.get("due_date", "")),
                ("Amount Payable", _money(voucher.get("amount"))),
            ]
        )
    )
    elements.append(Spacer(1, 0.3 * inch))
    elements.append(
        Paragraph(
            "Detach and present this voucher with payment at any Inland Revenue Division office, "
            "or quote the BIR Account Reference above when paying via e-Tax / linkt2pay.",
            _BODY,
        )
    )
    return _render(elements)


# ---------------------------------------------------------------------------
# Monthly PAYE / NIS / Health Surcharge payroll summary
# ---------------------------------------------------------------------------


def generate_payroll_summary_pdf(employer: dict, period_label: str, lines: list[dict]) -> bytes:
    elements = _header(
        "PAYE / NIS / Health Surcharge - Monthly Summary",
        [f"{employer.get('display_name', '')} &nbsp;|&nbsp; Period: {period_label}"],
    )

    rows = [("Employee", "Gross Pay", "NIS (Ee/Er)", "Health Surch. (Ee/Er)", "PAYE", "Net Pay")]
    totals = {"gross": Decimal("0"), "nis_ee": Decimal("0"), "nis_er": Decimal("0"), "hs_ee": Decimal("0"), "hs_er": Decimal("0"), "paye": Decimal("0"), "net": Decimal("0")}

    for line in lines:
        gross = Decimal(str(line.get("gross_pay", 0)))
        nis_ee = Decimal(str(line.get("nis_employee", 0)))
        nis_er = Decimal(str(line.get("nis_employer", 0)))
        hs_ee = Decimal(str(line.get("health_surcharge_employee", 0)))
        hs_er = Decimal(str(line.get("health_surcharge_employer", 0)))
        paye = Decimal(str(line.get("paye_deducted", 0)))
        net = Decimal(str(line.get("net_pay", 0)))

        rows.append(
            (
                line.get("employee_name", ""),
                _money(gross),
                f"{_money(nis_ee)} / {_money(nis_er)}",
                f"{_money(hs_ee)} / {_money(hs_er)}",
                _money(paye),
                _money(net),
            )
        )
        totals["gross"] += gross
        totals["nis_ee"] += nis_ee
        totals["nis_er"] += nis_er
        totals["hs_ee"] += hs_ee
        totals["hs_er"] += hs_er
        totals["paye"] += paye
        totals["net"] += net

    rows.append(
        (
            "TOTAL",
            _money(totals["gross"]),
            f"{_money(totals['nis_ee'])} / {_money(totals['nis_er'])}",
            f"{_money(totals['hs_ee'])} / {_money(totals['hs_er'])}",
            _money(totals["paye"]),
            _money(totals["net"]),
        )
    )

    table = Table(rows, colWidths=[1.6 * inch, 0.9 * inch, 1.3 * inch, 1.3 * inch, 0.8 * inch, 0.9 * inch])
    style = TableStyle(_TABLE_STYLE.getCommands())
    style.add("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold")
    style.add("LINEABOVE", (0, -1), (-1, -1), 1, colors.black)
    table.setStyle(style)
    elements.append(table)

    elements.append(Paragraph("Totals due for remittance to the Board of Inland Revenue / NIBTT:", _SECTION))
    elements.append(
        _kv_table(
            [
                ("Description", "Amount"),
                ("Total NIS (employee + employer)", _money(totals["nis_ee"] + totals["nis_er"])),
                ("Total Health Surcharge (employee + employer)", _money(totals["hs_ee"] + totals["hs_er"])),
                ("Total PAYE remitted", _money(totals["paye"])),
            ]
        )
    )

    return _render(elements)
